#!/usr/bin/env python3
"""The dlopen registry for a closed-world wasm32 program (musl wasm32's
dlopen): which libraries are linked in and
where each one's exported symbols are.

    dlreg.py LIB:KIND:NAME=LINKNAME ... > registry.c

LIB is the file name dlopen is asked for (ws2_32.so), KIND `data` or
`func`, NAME the symbol dlsym is asked for and LINKNAME what it was
renamed to when the library was compiled (-DNAME=LINKNAME)."""
import sys
from collections import OrderedDict

libs = OrderedDict()
for a in sys.argv[1:]:
    lib, kind, rest = a.split(':', 2)
    name, link = rest.split('=') if '=' in rest else (rest, rest)
    libs.setdefault(lib, []).append((kind, name, link))

print('/* Generated by wine/dlreg.py. Do not edit. */')
print('struct __gex_dl_sym { const char *name; void *addr; };')
print('struct __gex_dl_lib { const char *name; const struct __gex_dl_sym *syms; };')
for lib, syms in libs.items():
    for kind, name, link in syms:
        print(f'extern char {link}[];' if kind == 'data' else f'extern void {link}(void);')
ids = []
for k, (lib, syms) in enumerate(libs.items()):
    print(f'static const struct __gex_dl_sym syms{k}[] = {{')
    for kind, name, link in syms:
        print(f'    {{ "{name}", (void *){link} }},')
    print('    { 0, 0 }\n};')
    print(f'static const struct __gex_dl_lib lib{k} = {{ "{lib}", syms{k} }};')
    ids.append(f'&lib{k}')
print('const struct __gex_dl_lib *const __gex_dl_libs[] = { ' + ', '.join(ids + ['0']) + ' };')
