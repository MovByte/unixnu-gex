#!/usr/bin/env python3
"""ffi64/ffi.c's call table (64-bit Wine's libwayland, LP64 wasm64; wine64-deps.sh writes it
as ffi64.inc). A Wayland listener's arguments are i32 (ints,
fixeds, fds) or i64 (pointers), and a call_indirect must match the callee's
type exactly: one function per pattern, keyed by the argument count and a mask
of the 64-bit arguments. libwayland passes the listener's data and proxy
first (both pointers), so with three or more arguments only patterns
starting with two pointers are made; up to MAX arguments in all.

ffi_call takes the pattern's function from a table and makes one indirect
call. One switch over every pattern instead is a function of some
two thousand cases, which the link inlines into libwayland's dispatch_event:
V8's optimizing tier runs out of memory compiling that once it is hot."""
import sys
MAX = int(sys.argv[1]) if len(sys.argv) > 1 else 12
out = ['/* generated by ffi64/gen.py: do not edit */', '#define FFI64_MAX %d' % MAX]
table, base = [], []
for n in range(MAX + 1):
    fixed = 2 if n >= 3 else 0
    base.append(len(table))
    for rest in range(1 << (n - fixed)):
        mask = (rest << fixed) | ((1 << fixed) - 1)
        ts = ['long long' if mask >> i & 1 else 'int' for i in range(n)]
        proto = ', '.join(ts) or 'void'
        args = ', '.join('*(%s *)av[%d]' % (t, i) for i, t in enumerate(ts))
        name = 'ffi64_%d_%x' % (n, mask)
        out.append('static void %s(void (*fn)(void), void **av) { ((void (*)(%s))fn)(%s); }' % (name, proto, args))
        table.append(name)
out.append('static void (*const ffi64_calls[])(void (*)(void), void **) = {')
out += ['    %s,' % t for t in table]
out.append('};')
out.append('static const unsigned short ffi64_base[FFI64_MAX + 1] = { %s };' % ', '.join(map(str, base)))
out += ['/* the pattern\'s function, or 0 if there is none */',
        'static void (*ffi64_pick(unsigned n, unsigned mask))(void (*)(void), void **)', '{',
        '    if (n > FFI64_MAX) return 0;',
        '    if (n < 3) return ffi64_calls[ffi64_base[n] + mask];',
        '    if ((mask & 3) != 3) return 0;',
        '    return ffi64_calls[ffi64_base[n] + (mask >> 2)];', '}']
print('\n'.join(out))
