void* gexgen_proc(const char* name, const char* alias);

/* Each call site looks its function up once. */
#define GEX_GL_CALL(function, ...)                                                    \
    ([]() {                                                                           \
        static const auto p__ = reinterpret_cast<decltype(&function)>(gexgen_proc(#function, nullptr)); \
        return p__;                                                                   \
    }())(__VA_ARGS__)

void* gexgen_proc(const char* name, const char* alias) {
    void* f = reinterpret_cast<void*>(eglGetProcAddress(name));
    if (!f && alias) f = reinterpret_cast<void*>(eglGetProcAddress(alias));
    return f;
}

void gexgen_missing(const char* name) {
    static std::unordered_set<std::string> said;
    if (said.insert(name).second) fprintf(stderr, "gex-gl: the host's GL has no %s; the call does nothing\n", name);
}

