/* A framebuffer (kind 2) or renderbuffer (kind 3) name of the guest's, as the
 * host's: op 0 looks it up, generating a host name at its first use (a
 * GenFramebuffers, or a bind of a name the guest never generated), op 1
 * forgets it and says which host name to delete. 0 is 0. */
extern "C" uint32_t gexgl_native_object(uint32_t kind, uint32_t guest, uint32_t op) {
    if (!guest) return 0;
    auto& map = kind == 2 ? framebuffers : renderbuffers;
    auto it = map.find(guest);
    if (op == 1) {
        if (it == map.end()) return guest;
        const GLuint host = it->second;
        map.erase(it);
        return host;
    }
    if (it != map.end()) return it->second;
    GLuint host = 0;
    if (kind == 2) glGenFramebuffers(1, &host);
    else glGenRenderbuffers(1, &host);
    map[guest] = host;
    return host;
}

/* A shader (kind 0) or program (kind 1) host.rs created (host != 0) or
 * deleted (host == 0). */
extern "C" void gexgl_native_name(uint32_t kind, uint32_t guest, uint32_t host) {
    auto& map = kind == 0 ? shaders : programs;
    if (host) map[guest] = host;
    else map.erase(guest);
}
