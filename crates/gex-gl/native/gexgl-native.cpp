/* Run one generated command. 1 if it ran (its reply, possibly empty, at
 * *reply_out), 0 if the opcode is not one of them, -1 if it was malformed. */
extern "C" int gexgl_native_one(uint32_t op, const uint8_t* body, size_t len,
                                const uint8_t** reply_out, size_t* reply_len) {
    reply.clear();
    Reader a{body, body + len};
    const bool ok = one(op, a);
    const bool known = ok || !a.ok || op >= 1024;
    *reply_out = reply.data();
    *reply_len = reply.size();
    if (!known) return 0;
    if (!ok) return a.ok ? 0 : -1;
    return 1;
}

