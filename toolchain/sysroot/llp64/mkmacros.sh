#!/bin/sh
# Print llp64.h: the type-model macros clang predefines, as x86_64 MSVC's
# (the plugin changes the types; predefined macros are computed before it).
set -eu
echo '/* Generated by toolchain/sysroot/llp64/mkmacros.sh: LLP64 predefined macros on wasm64. */'
# wasm64 predefines the LP64 markers, which headers take for an LP64 long.
printf '#undef __LP64__\n#undef _LP64\n#define __GEX_LLP64__ 1\n'
# as x86_64 Windows compilers do (MinGW, clang-cl): headers key 64-bit
# Windows types on it (msvcrt's intptr_t)
printf '#ifndef _WIN64\n#define _WIN64 1\n#endif\n'
clang --target=x86_64-pc-windows-msvc -fshort-wchar -dM -E -x c /dev/null |
  grep -E '^#define __(SIZE|PTRDIFF|INTPTR|UINTPTR|INTMAX|UINTMAX|INT64|UINT64|INT_LEAST64|UINT_LEAST64|INT_FAST64|UINT_FAST64|LONG_MAX|LONG_WIDTH|SIZEOF_LONG|SIZEOF_LONG_DOUBLE|LDBL|WINT|SIZEOF_WINT_T|SIZEOF_SIZE_T|SIZEOF_PTRDIFF_T)' |
  grep -v LONG_LONG | sort |
  while read -r _ name value; do
    printf '#undef %s\n#define %s %s\n' "${name%%(*}" "$name" "$value"
  done
