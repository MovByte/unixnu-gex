#!/usr/bin/env python3
"""Generate crates/gex-kernel/src/darwin/sysno.rs from XNU's syscalls.master.

usage: tools/darwin-gen-sysno.py [--tag xnu-10063.141.1]

The table is fetched from Apple's open-source XNU at the tag (the default is
the one UniXNU's iPadOS 17.7 profile pins), with its conditionals evaluated
for the kernel an iPad runs: the RELEASE configuration of
config/MASTER.arm64.iPhoneOS. Every live entry becomes a constant named after
its function and NAMES maps numbers back to names for traces; ENOSYS lists
the entries that are `enosys` (ENOSYS, nothing else) and NSYSENT the size of
the table. Every other number is `nosys`, which also raises SIGSYS.
"""
import re
import sys
import urllib.request
from pathlib import Path

DEFAULT_TAG = "xnu-10063.141.1"
BASE = "https://raw.githubusercontent.com/apple-oss-distributions/xnu/{tag}/"
CONFIG = ("config/MASTER", "config/MASTER.arm64.iPhoneOS")
BUILD = "RELEASE"
OUT = Path(__file__).resolve().parent.parent / "crates/gex-kernel/src/darwin/sysno.rs"

ENTRY = re.compile(r"^(\d+)\s+\S+\s+\S+\s+\{\s*[^{}]*?\b([A-Za-z_][A-Za-z0-9_]*)\s*\(")
GROUP = re.compile(r"^#\s+([A-Z0-9_]+)\s*=\s*\[(.*)\]\s*$")
OPTION = re.compile(r"^\s*(?:options|pseudo-device)\s+([A-Za-z0-9_]+).*<([^>]*)>\s*$")


def fetch(tag, path):
    with urllib.request.urlopen(BASE.format(tag=tag) + path) as r:
        return r.read().decode()


def options(masters):
    """The options a build enables: each `options NAME # <tags>` line is on
    when one of its tags is in the build's expanded group list."""
    groups = {}
    for text in masters:
        for line in text.splitlines():
            m = GROUP.match(line)
            if m:
                groups[m.group(1)] = m.group(2).split()

    def expand(name, seen):
        out = set()
        for t in groups.get(name, []):
            if t in groups and t not in seen:
                seen.add(t)
                out |= expand(t, seen)
            else:
                out.add(t)
        return out

    tags = expand(BUILD, set())
    on = set()
    for text in masters:
        for line in text.splitlines():
            m = OPTION.match(line)
            if m and any(t.strip() in tags for t in m.group(2).split(",")):
                on.add(m.group(1))
    return on


def entries(text, on):
    """Live calls by name, `enosys` numbers, and the table size, with the
    `#if` blocks evaluated: a symbol is true when the build enables it."""
    live, enosys, top = {}, set(), 0
    stack = []
    for line in text.splitlines():
        d = re.match(r"^#\s*(if|ifdef|ifndef|else|endif)\b\s*([A-Za-z0-9_]*)", line)
        if d:
            kind, sym = d.groups()
            if kind in ("if", "ifdef"):
                stack.append(sym in on)
            elif kind == "ifndef":
                stack.append(sym not in on)
            elif kind == "else":
                stack[-1] = not stack[-1]
            else:
                stack.pop()
            continue
        if not all(stack):
            continue
        m = ENTRY.match(line)
        if not m:
            continue
        # The kernel's handler for some calls is sys_NAME; the call is NAME.
        nr, name = int(m.group(1)), re.sub(r"^sys_", "", m.group(2))
        top = max(top, nr + 1)
        if name == "enosys":
            enosys.add(nr)
        elif name != "nosys" and nr not in live.values():
            live.setdefault(name, nr)
    return sorted(live.items(), key=lambda kv: kv[1]), sorted(enosys), top


def main():
    argv = sys.argv[1:]
    tag = argv[1] if len(argv) > 1 and argv[0] == "--tag" else DEFAULT_TAG
    text = fetch(tag, "bsd/kern/syscalls.master")
    on = options([fetch(tag, p) for p in CONFIG])
    rows, enosys, top = entries(text, on)
    out = [
        "//! Darwin BSD system call numbers, generated by tools/darwin-gen-sysno.py",
        f"//! from XNU's bsd/kern/syscalls.master ({tag}, {BUILD} {CONFIG[1]}). Do not edit.",
        "",
    ]
    for name, nr in rows:
        out.append(f"pub const {name.upper().lstrip('_')}: u64 = {nr};")
    out += ["", "/// The number of entries in the table; any number past it is `nosys`.", f"pub const NSYSENT: u64 = {top};"]
    out += ["", "/// The entries that are `enosys`: ENOSYS and nothing more.", "pub const ENOSYS: &[u64] = &["]
    out += [f"    {nr}," for nr in enosys]
    out += ["];"]
    out += ["", "/// `(number, name)`, sorted by number.", "pub const NAMES: &[(u64, &str)] = &["]
    out += [f'    ({nr}, "{name}"),' for name, nr in rows]
    out += ["];", "", "/// The name of BSD call `nr`, for traces.", "pub fn name(nr: u64) -> Option<&'static str> {",
            "    NAMES.binary_search_by_key(&nr, |&(n, _)| n).ok().map(|i| NAMES[i].1)", "}", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {len(rows)} calls, {len(enosys)} enosys of {top} to {OUT}")


if __name__ == "__main__":
    main()
