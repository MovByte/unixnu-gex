#!/usr/bin/env python3
"""Generate crates/gex-kernel/src/darwin/sysno.rs from XNU's syscalls.master.

usage: tools/darwin-gen-sysno.py [syscalls.master | --tag xnu-10063.141.1]

With a tag (the default is the one UniXNU's iPadOS 17.7 profile pins), the
file is fetched from Apple's open-source XNU. Every live entry becomes a
constant named after its function, and NAMES maps numbers back to names
for traces.
"""
import re
import sys
import urllib.request
from pathlib import Path

DEFAULT_TAG = "xnu-10063.141.1"
URL = "https://raw.githubusercontent.com/apple-oss-distributions/xnu/{tag}/bsd/kern/syscalls.master"
OUT = Path(__file__).resolve().parent.parent / "crates/gex-kernel/src/darwin/sysno.rs"

ENTRY = re.compile(r"^(\d+)\s+\S+\s+\S+\s+\{\s*[^{}]*?\b([A-Za-z_][A-Za-z0-9_]*)\s*\(")
SKIP = {"nosys", "enosys"}


def source(argv):
    if argv and argv[0] != "--tag":
        return Path(argv[0]).read_text(), argv[0]
    tag = argv[1] if len(argv) > 1 else DEFAULT_TAG
    with urllib.request.urlopen(URL.format(tag=tag)) as r:
        return r.read().decode(), tag


def entries(text):
    seen = {}
    for line in text.splitlines():
        m = ENTRY.match(line)
        if not m:
            continue
        # The kernel's handler for some calls is sys_NAME; the call is NAME.
        nr, name = int(m.group(1)), re.sub(r"^sys_", "", m.group(2))
        if name in SKIP or nr in seen.values():
            continue
        seen.setdefault(name, nr)
    return sorted(seen.items(), key=lambda kv: kv[1])


def main():
    text, origin = source(sys.argv[1:])
    rows = entries(text)
    out = [
        "//! Darwin BSD system call numbers, generated by tools/darwin-gen-sysno.py",
        f"//! from XNU's bsd/kern/syscalls.master ({origin}). Do not edit.",
        "",
    ]
    for name, nr in rows:
        out.append(f"pub const {name.upper().lstrip('_')}: u64 = {nr};")
    out += ["", "/// `(number, name)`, sorted by number.", "pub const NAMES: &[(u64, &str)] = &["]
    out += [f'    ({nr}, "{name}"),' for name, nr in rows]
    out += ["];", "", "/// The name of BSD call `nr`, for traces.", "pub fn name(nr: u64) -> Option<&'static str> {",
            "    NAMES.binary_search_by_key(&nr, |&(n, _)| n).ok().map(|i| NAMES[i].1)", "}", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {len(rows)} calls to {OUT}")


if __name__ == "__main__":
    main()
